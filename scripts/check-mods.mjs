// Checks every mod folder is a complete Herdr gallery entry and that its JavaScript parses.
// A mod folder is a top-level folder holding RECIPE.md.
import { readdirSync, readFileSync, existsSync, statSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";

const errors = [];
const root = process.cwd();
const folders = readdirSync(root).filter((d) => !d.startsWith(".") && statSync(join(root, d)).isDirectory() && existsSync(join(root, d, "RECIPE.md")));
if (!folders.length) errors.push("no mod folders (top-level folders with RECIPE.md)");

for (const f of folders) {
  for (const need of ["README.md", "RECIPE.md", "preview.png"]) if (!existsSync(join(f, need))) errors.push(`${f}: missing ${need}`);
  const recipe = readFileSync(join(f, "RECIPE.md"), "utf8");
  for (const h of ["## What you see", "## How it behaves", "## Built from", "## Watch out", "## Done when"]) if (!recipe.includes(h)) errors.push(`${f}/RECIPE.md: missing "${h}"`);
  const mods = existsSync(join(f, "mods")) ? readdirSync(join(f, "mods")) : [];
  if (!mods.length) errors.push(`${f}: no mods/<name>/ folder`);
  for (const m of mods) {
    const dir = join(f, "mods", m);
    if (!existsSync(join(dir, "main.js"))) errors.push(`${dir}: missing main.js`);
    try { JSON.parse(readFileSync(join(dir, "mod.json"), "utf8")); } catch (e) { errors.push(`${dir}/mod.json: ${e.message}`); }
    for (const file of readdirSync(dir).filter((n) => n.endsWith(".js"))) {
      const src = readFileSync(join(dir, file), "utf8");
      // Herdr's QuickJS rejects ?? mixed with || or && on one level without parentheses.
      src.split("\n").forEach((line, i) => {
        if (/\?\?[^()]*(\|\||&&)|(\|\||&&)[^()]*\?\?/.test(line.replace(/\/\/.*$/, "").replace(/(["'`])(?:\\.|(?!\1).)*\1/g, '""'))) {
          errors.push(`${dir}/${file}:${i + 1}: ?? mixed with || or && needs parentheses`);
        }
      });
      try { execFileSync(process.execPath, ["--check", join(dir, file)], { stdio: "pipe" }); }
      catch (e) { errors.push(`${dir}/${file}: ${String(e.stderr).split("\n").slice(0, 4).join(" ")}`); }
    }
    // Herdr writes these next to a mod; they must not be published.
    for (const gen of ["jsconfig.json", "gpui-kit.d.ts", "herdr.d.ts"]) if (existsSync(join(dir, gen))) errors.push(`${dir}/${gen}: generated by Herdr, don't commit it`);
  }
}

if (errors.length) { for (const e of errors) console.error(e); process.exit(1); }
console.log(`Mod folders passed: ${folders.join(", ")}`);
